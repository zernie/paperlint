/**
 * markdown.mjs — разбор разметки для ВСЕГО, что в этой репе читает markdown.
 *
 * Потребители трёх видов: два advisory-линтера (`kb-lint`, `paper-lint` — через
 * ре-экспорт из `lint-core.mjs`) и скрипты скиллов (`tighten-paper/structure.mjs`,
 * `grade-paper-writing/prose-lint.mjs`, `paper-pipeline/scripts/*`). Поэтому дом
 * здесь, а не в ядре линтеров: импортировать «ядро линтеров» из скрипта скилла
 * было бы враньём про направление зависимости.
 *
 * НИЧЕГО НЕ ПРОВЕРЯЕТ И НЕ ПЕЧАТАЕТ: текст на входе, данные на выходе. Что делать
 * с отсутствующим парсером, решает вызывающий, и решения РАЗНЫЕ:
 *   • линтер — деградирует и ГРОМКО об этом нудит (блокирующий гейт при этом
 *     обязан продолжать работать: PreToolUse считает блоком только код 2, и
 *     падение на импорте выключало бы гейт молча);
 *   • скрипт скилла — падает через `requireMarkdown()`, потому что его вывод
 *     идёт в гейты пайплайна, и «0 заголовков» там читается как факт о статье.
 */
// ПРАВИЛО (`CLAUDE.md`, 2026-08-11): структуру markdown разбираем ПАРСЕРОМ, а не
// регулярками. Наступили четыре раза, три из них — один и тот же дефект: JS `\b`
// определён над `[A-Za-z0-9_]`, и рядом с кириллической буквой границы слова НЕТ,
// флаг `u` этого не меняет. `## Приложение` не матчилось ни разу за всю жизнь
// проверки. У заголовка из парсера есть УРОВЕНЬ и ТЕКСТ — «границы слова» в
// природе не существует, и ошибку становится НЕЧЕМ выразить.
//
// Помощник переехал сюда из `paper-lint.mjs` 2026-08-11, когда появился второй
// потребитель (`kb-lint.checkRejectedRowsCited` резал `topics/*.md` на секции
// регуляркой — и делал это ДВУМЯ СТРОКАМИ ВЫШЕ собственного комментария про этот
// самый баг). Условие переноса было записано заранее, ровно на этот случай.
//
// 🔴 ИМПОРТ НЕОБЯЗАТЕЛЬНЫЙ. До 11.08 у хуков не было ни одной зависимости, и голый
// top-level `import` менял форму отказа: нет `node_modules` → падение с кодом 1 →
// **блокирующий гейт `pre` в paper-lint перестаёт блокировать молча**, потому что
// PreToolUse считает блоком только код 2. Замерено: `ERR_MODULE_NOT_FOUND`, exit 1.
let md = null;
try {
  const { default: MarkdownIt } = await import("markdown-it");
  md = new MarkdownIt();
} catch {
  md = null;
}

/**
 * Разрешился ли парсер. Линтер обязан проверить это САМ и сказать вслух, что его
 * заголовочные проверки выключены: `headings()` при отсутствии парсера отдаёт
 * пустой список, а тихая пустота читается как «в документе нет заголовков», то
 * есть как чистый документ. Нудж живёт в линтерах, потому что этот файл по
 * контракту (см. шапку) не имеет права породить ни одной находки.
 */
export const MD_AVAILABLE = () => md !== null;

/**
 * Фронтматтер ГАСИТСЯ пробелами, а не вырезается: смещения обязаны остаться
 * прежними, потому что проверки режут документ по offset'у. Гасить необходимо —
 * в блочном скаляре YAML строка с отступом в два пробела (`  ## Foo`) для
 * CommonMark настоящий ATX-заголовок, и без гашения фронтматтер начинает
 * поставлять секции.
 */
const FRONTMATTER_RE = /^---[ \t]*\r?\n[\s\S]*?\r?\n---[ \t]*(?=\r?\n|$)/;
export function blankFrontmatter(text) {
  const m = FRONTMATTER_RE.exec(text);
  return m ? m[0].replace(/[^\n]/g, " ") + text.slice(m[0].length) : text;
}

/**
 * Тело фронтматтера (между оградами), или `null` — если файл открывается без него.
 *
 * Заведено 2026-08-20, когда восемь мест в `.claude/**` резали фронтматтер восемью
 * слегка разными регулярками: часть знала про `\r\n`, часть нет; часть требовала
 * перевод строки после закрывающей ограды, часть нет. Разница между ними — это не
 * стиль, это разный ответ на одном и том же файле.
 *
 * ⚠️ Это НЕ парсер и не претендует: `---`-фронтматтер не является markdown, ни один
 * markdown-парсер его не моделирует (разбор — в корневом `CLAUDE.md`, «Рассмотрено и
 * отклонено: gray-matter»). Ценность здесь — одна ограда вместо восьми, а разбор
 * ЗНАЧЕНИЙ делает `js-yaml` у вызывающего.
 */
export function frontmatterBlock(text) {
  const m = FRONTMATTER_RE.exec(text);
  if (!m) return null;
  const inner = m[0].replace(/^---[ \t]*\r?\n/, "").replace(/\r?\n---[ \t]*$/, "");
  return inner;
}

/**
 * Документ БЕЗ фронтматтера — блок вырезан вместе с переводом строки за ним.
 *
 * Отличается от {@link blankFrontmatter} тем, что смещения СДВИГАЮТСЯ. Обе формы
 * нужны и обе уже использовались: гашение — там, где позиции символов потом
 * показываются пользователю; вырезание — там, где текст просто считают. Выбирать
 * по тому, что делает вызывающий, а не по вкусу.
 */
export function stripFrontmatter(text) {
  const m = FRONTMATTER_RE.exec(text);
  return m ? text.slice(m[0].length).replace(/^\r?\n/, "") : text;
}

/** Смещения начал строк — чтобы `token.map` стал позицией в исходной строке. */
function lineStarts(text) {
  const out = [0];
  for (let i = 0; i < text.length; i++) if (text[i] === "\n") out.push(i + 1);
  return out;
}

/**
 * Все заголовки документа: `[{ depth, text, line, offset }]`, в порядке следования.
 *
 * `offset` — индекс начала строки заголовка В ТОМ ЖЕ тексте, что передан сюда, в
 * единицах `slice`/`indexOf` (UTF-16), потому что ровно ими проверки и режут
 * документ. `line` — 0-based номер строки. `text` — без решёток, обрезан по краям.
 *
 * ⚠️ ТОЛЬКО ATX (`## Заголовок`). Setext (`Заголовок\n---`) сознательно НЕ считается
 * заголовком: в этой базе `---` — прозаический разделитель, и абзац, под которым он
 * стоит без пустой строки, по CommonMark стал бы заголовком 2-го уровня. Прежние
 * регэкспы знали только ATX, так что это сохранение контракта, а не сужение.
 */
export function headings(text) {
  if (md === null) return [];
  const toks = md.parse(blankFrontmatter(text), {});
  const starts = lineStarts(text);
  const out = [];
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    if (t.type !== "heading_open" || !t.map) continue;
    if (!t.markup || !t.markup.startsWith("#")) continue; // setext — см. оговорку выше
    const inline = toks[i + 1];
    out.push({
      depth: Number(t.tag.slice(1)),
      text: inline?.type === "inline" ? inline.content.trim() : "",
      line: t.map[0],
      offset: starts[t.map[0]] ?? 0,
    });
  }
  return out;
}

/** Смещения тематических разрывов `---` (в этой базе — прозаический разделитель). */
export function thematicBreaks(text) {
  if (md === null) return [];
  const starts = lineStarts(text);
  return md
    .parse(blankFrontmatter(text), {})
    .filter((t) => t.type === "hr" && t.map)
    .map((t) => starts[t.map[0]] ?? 0);
}

/**
 * Тело секции: от строки ПОСЛЕ заголовка, подходящего под `match`, до следующего
 * заголовка ТОГО ЖЕ ИЛИ МЕНЬШЕГО уровня. `{ heading, body }` или `null`.
 *
 * `match` — регулярка по тексту заголовка ИЛИ предикат от `{depth,text,line,offset}`.
 *
 * Уровень-или-меньше, а не «ровно `##`»: подраздел `###` внутри секции её не
 * заканчивает — ровно так вели себя прежние выражения с лукахэдом `(?=\n## )`.
 * Регулярка этого различия не знает в принципе: у неё нет понятия уровня.
 *
 * `depth` — ПОТОЛОК уровня самого заголовка. Без него `### Abstract`, процитированный
 * в приложении, становится аннотацией — а её судят с порогом НОЛЬ.
 *
 * `stopAtRule` дополнительно обрывает секцию на первом `---`. Это НЕ структура
 * markdown, а конвенция статьи, и она сохранена намеренно: у заключения `---` стоит
 * перед приложениями, и без границы секция без следующего `##` дотянулась бы до
 * конца файла.
 *
 * 🔴 ОБЪЕДИНЁННАЯ ВЕРСИЯ. 2026-08-11 эта функция завелась ОДНОВРЕМЕННО в двух местах:
 * здесь (для `kb-lint`) и в `paper-lint.mjs` (богаче — с потолком уровня, заголовком
 * в ответе и `stopAtRule`). Обе писались в один час двумя параллельными проходами,
 * ни один не видел другого. Слито в богатую версию: слабая была подмножеством, и
 * оставить обе значило бы разойтись в поведении при следующей же правке.
 */
export function sectionBody(text, match, { depth = 6, stopAtRule = false } = {}) {
  const test = typeof match === "function" ? match : (h) => match.test(h.text);
  const hs = headings(text);
  const i = hs.findIndex((h) => h.depth <= depth && test(h));
  if (i === -1) return null;
  const h = hs[i];
  const next = hs.slice(i + 1).find((n) => n.depth <= h.depth);
  let end = next ? next.offset : text.length;
  if (stopAtRule) {
    const hr = thematicBreaks(text).find((o) => o > h.offset && o < end);
    if (hr !== undefined) end = hr;
  }
  // Тело — со строки ПОСЛЕ заголовка: сам заголовок в секцию не входит, так же как
  // его не захватывала группа прежних выражений.
  const nl = text.indexOf("\n", h.offset);
  const start = nl === -1 || nl + 1 > end ? end : nl + 1;
  return { heading: h, body: text.slice(start, end) };
}

/**
 * Нарезка документа на куски «заголовок + всё до следующего заголовка ИЗ ТОГО ЖЕ
 * ДИАПАЗОНА уровней». → `[{ heading, raw, body }]`.
 *
 * Это ровно то, что четыре скрипта делали как `split(/^(?=## )/m)` и
 * `split(/^(?=#{2,3} )/m)`. Форма выражения врала о намерении: «две-три решётки»
 * — это про СИМВОЛЫ, а нужен УРОВЕНЬ, и `#{2,3}` заодно ловил решётку внутри
 * ```-блока, то есть цитату чужой статьи резал как собственную секцию.
 *
 * `heading` — `null` у нулевого элемента (преамбула до первого заголовка). Он
 * есть ВСЕГДА, в том числе пустой: прежний `split` тоже всегда отдавал нулевым
 * элементом кусок до первого разделителя, и вызывающие на это опираются
 * (`sub === chunk` в `artifact-coverage` значило «подсекций нет»).
 *
 * `raw` — СО строкой заголовка (по ней считают `§`-ссылки и жирные числа,
 * которые бывают и в самом заголовке), `body` — без неё (по ней считают слова).
 *
 * 2026-08-11: вынесено сюда, а не скопировано в каждый скрипт, потому что
 * граница куска — единственное место, где легко ошибиться на единицу, и такая
 * ошибка уже случалась (`recordBlock` в `skill-corpus.mjs` отдавал один символ
 * «#» на всех 21 скилле).
 */
export function splitSections(text, { min = 2, max = 6 } = {}) {
  const hs = headings(text).filter((h) => h.depth >= min && h.depth <= max);
  const out = [];
  const preEnd = hs.length ? hs[0].offset : text.length;
  out.push({ heading: null, raw: text.slice(0, preEnd), body: text.slice(0, preEnd) });
  for (let i = 0; i < hs.length; i++) {
    const h = hs[i];
    const end = i + 1 < hs.length ? hs[i + 1].offset : text.length;
    const nl = text.indexOf("\n", h.offset);
    const bodyStart = nl === -1 || nl + 1 > end ? end : nl + 1;
    out.push({ heading: h, raw: text.slice(h.offset, end), body: text.slice(bodyStart, end) });
  }
  return out;
}

/**
 * Текст без содержимого ```-блоков (сами строки фенсов тоже уходят).
 *
 * Через парсер, а не `/```[\s\S]*?```/g`: тот паттерн склеивает конец одного блока
 * с началом следующего при нечётном числе фенсов, не знает `~~~`-фенсов и фенсов с
 * отступом, и молча съедает прозу между блоками.
 *
 * `blank: true` — строки блока НЕ удаляются, а ЗАМЕНЯЮТСЯ на пустые. Разница не
 * косметическая: удаление строк СКЛЕИВАЕТ абзац перед блоком с абзацем после него,
 * а код-блок — это граница блока, и по ту сторону начинается другой абзац.
 * Замерено 2026-08-11 на `<papers-root>/<paper>/README.md`: `prose-lint` считал там
 * 82 предложения, после удаления строк стал 81 — лид-абзац «**Команды
 * воспроизведения:**» слился с текстом ПОСЛЕ блока в одно предложение. Это ровно
 * тот отказ, против которого в самом `prose-lint` написано «Paragraph and heading
 * boundaries END a sentence», и он инфлирует счётчик утверждений на предложение —
 * порог, по которому файл выдаёт находки. Прежняя регулярка границу сохраняла
 * (оставляла по переводу строки с каждой стороны), так что `blank` — это ещё и
 * сохранение прежнего поведения там, где оно было верным.
 */
/**
 * СОДЕРЖИМОЕ огороженных блоков — обратная сторона `stripFences`.
 *
 * Заведена 08.09.2026 для проверки «путь как аргумент команды внутри ```-блока»
 * (шестая форма ссылки). Своя регулярка на ограду там была бы седьмым экземпляром
 * класса, за который эта база уже платила: `/^```[\s\S]*?^```/gm` не знает про
 * вложенные ограды и про `~~~`, а парсер знает — у токена `fence` есть `content`.
 *
 * Нет парсера — возвращает пустой список, и вызывающий обязан это пережить: у хуков
 * деградация допустима (см. модульный комментарий), а тихий откат к регулярке
 * означал бы работающую деградированную версию, которую никто не заметит.
 */
export function fences(text) {
  if (md === null) return [];
  const out = [];
  for (const t of md.parse(blankFrontmatter(text), {}))
    if (t.type === "fence" || t.type === "code_block") out.push(t.content);
  return out;
}

export function stripFences(text, { blank = false } = {}) {
  if (md === null) return text;
  const lines = text.split("\n");
  const drop = new Set();
  for (const t of md.parse(blankFrontmatter(text), {}))
    if ((t.type === "fence" || t.type === "code_block") && t.map)
      for (let i = t.map[0]; i < t.map[1]; i++) drop.add(i);
  return blank
    ? lines.map((l, i) => (drop.has(i) ? "" : l)).join("\n")
    : lines.filter((_, i) => !drop.has(i)).join("\n");
}


/**
 * Для СКРИПТОВ, а не для хуков: падает, если парсера нет.
 *
 * У линтера деградация допустима — он advisory и умеет сказать вслух. Скрипт
 * скилла отдаёт числа в гейт пайплайна, и пустой список заголовков там неотличим
 * от «в статье нет секций». Уверенный ноль в этой репе уже четырежды читался как
 * находка; здесь он невыразим.
 */
export function requireMarkdown() {
  if (MD_AVAILABLE()) return;
  console.error(
    "markdown-it не разрешается — этот скрипт разбирает разметку парсером и без него " +
      "выдал бы уверенный ноль вместо ошибки. Лечится `npm i` в корне репозитория.",
  );
  process.exit(2);
}

/**
 * Таблицы GFM — строки, ячейки и диапазон строк, ПАРСЕРОМ.
 *
 * Единственный потребитель на 2026-08-20 — `crosspost-article`, которому надо
 * переложить таблицу в моноширинный блок для площадки без таблиц (Medium). Живёт
 * здесь, а не в скилле, по правилу «разметку разбираем парсером, и в одном месте»:
 * таблицу регуляркой отличают от строки текста с палками только по соседям, и это
 * ровно тот класс, что уже стоил этой репе 27 мест.
 *
 * Возвращает `{ line, endLine, rows }`, где `rows[0]` — шапка; строка выравнивания
 * (`| --- |`) выброшена, потому что в моноширинном выводе ей нечего выражать.
 */
/**
 * Абзацы документа — диапазоны строк `paragraph_open`, ПАРСЕРОМ. `[{ line, endLine }]`.
 *
 * Единственный потребитель на 2026-08-21 — `crosspost-article`: исходники блога
 * жёстко перенесены по колонке (редакторская привычка, не markdown), а площадки
 * рендерят одиночный `\n` внутри абзаца ПО-РАЗНОМУ — dev.to (Redcarpet) держит его
 * буквальным переносом, и абзац приезжает рваным на короткие строки ровно по
 * границам исходного файла. На Medium дефекта нет не потому, что площадка честнее,
 * а потому что вставка идёт через «Import a story» — импортёр берёт УЖЕ
 * ОТРЕНДЕРЕННУЮ страницу сайта (там переносы давно схлопнуты браузером), а не
 * сырой markdown.
 *
 * Диапазон РОВНО тот, что даёт `t.map` на `paragraph_open` — то есть code-fence,
 * заголовок, таблица, список (в TIGHT-списке пункт вообще не заворачивается в
 * `paragraph_open`, у него нет отдельного абзаца) под функцию не попадают
 * автоматически, конструкцией парсера, а не отдельной проверкой типа строки.
 */
export function paragraphs(text) {
  if (md === null) return [];
  return md
    .parse(blankFrontmatter(text), {})
    .filter((t) => t.type === "paragraph_open" && t.map)
    .map((t) => ({ line: t.map[0], endLine: t.map[1] }));
}

export function tables(text) {
  if (md === null) return [];
  const lines = blankFrontmatter(text).split("\n");
  const out = [];
  for (const t of md.parse(blankFrontmatter(text), {})) {
    if (t.type !== "table_open" || !t.map) continue;
    const rows = [];
    for (let i = t.map[0]; i < t.map[1]; i++) {
      const raw = lines[i];
      if (/^\s*\|?[\s:|-]+\|?\s*$/.test(raw) && raw.includes("-")) continue; // выравнивание
      rows.push(
        raw
          .replace(/^\s*\|/, "")
          .replace(/\|\s*$/, "")
          .split("|")
          .map((c) => c.trim()),
      );
    }
    out.push({ line: t.map[0], endLine: t.map[1], rows });
  }
  return out;
}
