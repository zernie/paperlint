/**
 * WHERE A BUILD'S BIBLIOGRAPHY COMES FROM (paperlint#708). The `.aux` names the databases
 * (`\bibdata`) and the style (`\bibstyle`); bibtex reads them and writes `paper.bbl`, which the next
 * pdflatex pass typesets. Nothing in a paper declares its kind: it is TeX's convention plus which
 * files exist. So the build decides from what `kpsewhich` finds and what is on disk:
 *
 *   no database named                                   → none: nothing for bibtex to do
 *   every database and the style found                  → run-bibtex
 *   one not found, and a paper.bbl on disk              → shipped-bbl: typeset it as it is, never
 *                                                         bibtex, the missing files named
 *   one not found, and no paper.bbl                     → missing: stop, naming them
 *
 * This is latexmk's default (`$bibtex_use = 1`: "only use bibtex or biber if the bib file(s)
 * exist"), whose manual names the case: with the bib files missing and the bbl provided, running
 * bibtex "will result in incorrect overwriting of the precious bbl files".
 *
 * 🔴 WHY bibtex IS NEVER RUN ON WHAT IT CANNOT READ. bibtex truncates `paper.bbl` before it reads
 * anything, and an error leaves it truncated: measured on a real paper, 17,682 → 49 bytes for a
 * missing `.bib`, 0 bytes for `\bibliographystyle{nosuchstyle}`.
 *
 * ⚠️ WHAT THIS DOES NOT GUARD. A paper.bbl shipped beside a `.bib` that IS found is regenerated by
 * bibtex — the `.bib` is the source, and the `bib` rules judge only what bibtex opened. A `.bib`
 * bibtex cannot parse still truncates that paper.bbl; the build then fails, naming the error.
 */

/** A file bibtex would read (`refs.bib`, `plain.bst`), and whether `kpsewhich` found it. */
export interface BibLookup {
  readonly name: string;
  readonly found: boolean;
}

export type BibSource =
  | { readonly kind: "none" }
  | { readonly kind: "run-bibtex" }
  /** The paper.bbl on disk, typeset as it is; `missing` names what bibtex could not read. */
  | { readonly kind: "shipped-bbl"; readonly missing: readonly string[] }
  /** No `.bbl` to fall back on, and these cannot be read. */
  | { readonly kind: "missing"; readonly missing: readonly string[] };

export function bibSource(facts: {
  readonly databases: readonly BibLookup[];
  /** Null when the `.aux` names no style. */
  readonly style: BibLookup | null;
  /** Whether a paper.bbl is on disk. */
  readonly bbl: boolean;
}): BibSource {
  if (facts.databases.length === 0) return { kind: "none" };
  const missing = [...facts.databases, ...(facts.style ? [facts.style] : [])]
    .filter((l) => !l.found)
    .map((l) => l.name);
  if (missing.length === 0) return { kind: "run-bibtex" };
  return facts.bbl
    ? { kind: "shipped-bbl", missing }
    : { kind: "missing", missing };
}
